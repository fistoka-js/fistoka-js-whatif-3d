// Catalogue generation (docs/CATALOG.md and kit/catalog.json) and timeline.json shape and sound rules.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { catalogData, catalogMarkdown } from '../tools/catalog.mjs';
import { buildTimeline } from '../tools/timeline.mjs';
import { catalog } from '../kit/engine/registry.js';
import { resolve, demoShow, REPO, SFX_FILES } from './helpers.mjs';

test('catalog.json lists every prop, env, action and camera option with params, defaults and docs', () => {
  const d = catalogData();
  assert.deepEqual(Object.keys(d.props), Object.keys(catalog.props));
  assert.deepEqual(Object.keys(d.envs), Object.keys(catalog.envs));
  assert.deepEqual(Object.keys(d.actions), Object.keys(catalog.actions));
  assert.deepEqual(d.props.planet.params.look.values, ['earth', 'moon', 'mars', 'gas', 'ice', 'lava']);
  assert.equal(d.props.planet.params.look.default, 'earth');
  assert.ok(d.props.planet.animatable.atmosphere.doc);
  assert.equal(d.props.beam.stageSpace, true);
  assert.equal(d.actions.appear.fields.style.default, 'pop');
  assert.equal(d.actions.appear.prop, 'required');
  assert.ok(d.camera.move.options.push_in);
  for (const a of Object.values(d.actions)) assert.ok(a.doc);
  // Compact enough to paste into a prompt.
  // Raised from 40000 in round 2 (four mechanism props, dials/bindings/continue docs); the prompt uses catalog_text.py's shorter text.
  assert.ok(JSON.stringify(d).length < 48000);
  assert.ok(d.transitions.dive && d.dials && d.bindings && d.continue && d.dialKeyFields.at);
  assert.deepEqual(d.envs.studio.dialParams, ['color']);
});

test('CATALOG.md has a section per prop, env and action', () => {
  const md = catalogMarkdown(catalogData());
  for (const n of [...Object.keys(catalog.props), ...Object.keys(catalog.envs), ...Object.keys(catalog.actions)]) assert.match(md, new RegExp(`^### ${n}$`, 'm'));
  assert.match(md, /Generated by `node tools\/catalog\.mjs`/);
});

test('the catalog tool writes both files', () => {
  execFileSync(process.execPath, [path.join(REPO, 'tools/catalog.mjs')], { encoding: 'utf8' });
  const json = JSON.parse(fs.readFileSync(path.join(REPO, 'kit/catalog.json'), 'utf8'));
  assert.deepEqual(json, JSON.parse(JSON.stringify(catalogData())));
  assert.ok(fs.readFileSync(path.join(REPO, 'docs/CATALOG.md'), 'utf8').includes('### planet'));
});

test('timeline.json: exact shape, shots match the show, events sorted and named like the sfx files', () => {
  const { show } = resolve(demoShow());
  const tl = buildTimeline(show);
  assert.deepEqual(Object.keys(tl), ['duration', 'shots', 'events']);
  assert.equal(tl.duration, 54.7);
  assert.deepEqual(tl.shots[1], { id: 'no-blue', start: 5, end: 13.72 });
  for (const e of tl.events) {
    assert.deepEqual(Object.keys(e), ['t', 'sfx', 'why']);
    assert.ok(SFX_FILES.includes(e.sfx), e.sfx);
  }
  for (let i = 1; i < tl.events.length; i++) assert.ok(tl.events[i].t >= tl.events[i - 1].t);
  const at = (t, sfx) => tl.events.some(e => Math.abs(e.t - t) < 0.01 && e.sfx === sfx);
  assert.ok(!at(0, 'whoosh'), 'no whoosh at t = 0');
  assert.ok(at(5, 'whoosh'), 'shot change');
  assert.ok(at(3.82, 'buzz'), 'icon x');
  assert.ok(at(34.54, 'chime'), 'icon check');
  assert.ok(at(4.12, 'rumble'), 'camera shake');
  assert.ok(at(24.02, 'tick'), 'count');
  assert.ok(at(5, 'pop') || at(5.0, 'whoosh'), 'appear sun');
  assert.ok(at(28.54, 'shimmer'), 'glow up');
  assert.ok(!tl.events.some(e => /disappear/.test(e.why)), 'disappear is silent');
});

test('sfx action: "rise" replaces nearby sounds; "none" silences them', () => {
  const { show } = resolve(demoShow());
  const tl = buildTimeline(show);
  assert.ok(tl.events.some(e => e.t === 11.52 && e.sfx === 'rise'));
  // "pinball" (27.36): the photon's appear pop is silenced by the sfx "none" there.
  assert.ok(!tl.events.some(e => Math.abs(e.t - 27.36) <= 0.25));
});
